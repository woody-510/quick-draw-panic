#define BGM_VOLUME_PAUSE    0.3f    /* ポーズ時のBGM音量 */

/* --- テクスチャ読み込み --- */
#define TEXTURE_LOAD_SIZE   256     /* GPU節約のため、読み込み後にリサイズするサイズ */

/* --- タイトル画面のスライドショー --- */
#define SLIDE_INTERVAL      3.0f    /* 画像の切り替え間隔（秒） */
