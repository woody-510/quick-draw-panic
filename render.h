/* =============================================================================
 * render.h — 描画関数の宣言
 * =============================================================================
 * 【このファイルの役割】
 * render.c で実装されている描画関数の「看板」。
 * main.c がこれらの関数を呼び出して画面を描画する。
 *
 * 【初心者向けメモ】
 * render（レンダー）= 「描画する」という意味。
 * このファイルの関数は画面に絵を描くことだけを担当し、
 * ゲームのルール（ロジック）には一切触れない。
 * ========================================================================== */

#ifndef RENDER_H
#define RENDER_H

#include "game.h"   /* GameState, Texture2D などの定義を使うため */

/* --------------------------------------------------------------------------
 * 画面別の描画関数
 * --------------------------------------------------------------------------
 * 各関数は BeginDrawing()〜EndDrawing() の間で呼び出される。
 * ClearBackground() は呼び出し元（main.c）で行うので、
 * これらの関数内では行わない。
 * -------------------------------------------------------------------------- */

/* DrawTitleScreen: タイトル画面を描画する
 * 表示内容: ロゴ、モード選択ボタン3つ、スコア閲覧ボタン、背景スライドショー */
void DrawTitleScreen(void);

/* DrawPlayingScreen: ゲームプレイ画面を描画する
 * 表示内容: 的（疑似3D）、HUD（タイマー/スコア/ステージ名）、
 *           ポーズボタン、エフェクト（白フラッシュ等） */
void DrawPlayingScreen(void);

/* DrawPauseScreen: ポーズ画面を描画する
 * 表示内容: 半透明黒オーバーレイ + 再開/リトライ/タイトルの3ボタン
 * ※背景にはゲームプレイ画面がそのまま表示される（その上に重ねる） */
void DrawPauseScreen(void);

/* DrawCountdownScreen: カウントダウン画面を描画する
 * 表示内容: ゲームプレイ画面（停止中）の上に、大きな数字「3」「2」「1」 */
void DrawCountdownScreen(void);

/* DrawResultScreen: リザルト画面を描画する
 * 表示内容: 今回のスコア、自己ベスト、NEW RECORD表示、戻るボタン */
void DrawResultScreen(void);

/* DrawScoresScreen: スコア一覧画面（ランキング）を描画する
 * 表示内容: 3モードのTOP5ランキング、戻るボタン */
void DrawScoresScreen(void);

#endif /* RENDER_H */
