/* ==========================================================================
 * ポーズ画面の更新処理
 * ==========================================================================
 * ポーズ中（SCREEN_PAUSE）に毎フレーム呼ばれる。
 * 3つのボタン（再開 / リトライ / タイトルへ戻る）のクリック判定を行う。
 * ========================================================================== */

void UpdatePause(float dt)
{
    /* dt は使わないが、インターフェースの統一のために受け取る */
    (void)dt;

    if (IsMouseButtonPressed(MOUSE_BUTTON_LEFT))
    {
        Vector2 pos = GetMousePosition();

        /* -----------------------------------------------------------
         * 3つのボタンの矩形定義
         * -----------------------------------------------------------
         * 画面中央に縦に並べて配置。
         * y=300: 再開（Resume）
         * y=390: リトライ（Retry）
         * y=480: タイトルへ（Title） */

        /* 再開ボタン */
        Rectangle btnResume = {
            (float)(SCREEN_WIDTH - BUTTON_WIDTH) / 2.0f,
            300.0f,
            (float)BUTTON_WIDTH,
            (float)BUTTON_HEIGHT
        };

        /* リトライボタン */
        Rectangle btnRetry = {
            (float)(SCREEN_WIDTH - BUTTON_WIDTH) / 2.0f,
            390.0f,
            (float)BUTTON_WIDTH,
            (float)BUTTON_HEIGHT
        };

        /* タイトルへ戻るボタン */
        Rectangle btnTitle = {
            (float)(SCREEN_WIDTH - BUTTON_WIDTH) / 2.0f,
            480.0f,
            (float)BUTTON_WIDTH,
            (float)BUTTON_HEIGHT
        };

        /* --- 再開ボタン ---
         * カウントダウン画面に遷移。3→2→1→ゲーム再開 の流れ。
         * いきなりプレイ画面に戻ると「不意打ち」になるので、
         * カウントダウンで準備時間を設ける。 */
        if (CheckCollisionPointRec(pos, btnResume))
        {
            game.screen = SCREEN_COUNTDOWN;       /* カウントダウン画面へ */
            game.countdownNumber = 3;              /* 3からカウントダウン開始 */
            game.countdownTimer = COUNTDOWN_INTERVAL; /* 1秒間隔 */
            return;
        }

        /* --- リトライボタン ---
         * 現在のモードで最初からやり直す。
         * InitGame() が全ての状態をリセットする。 */
        if (CheckCollisionPointRec(pos, btnRetry))
        {
            InitGame(game.mode); /* 同じモードで再初期化 */
            return;
        }

        /* --- タイトルへ戻るボタン ---
         * ゲームを中断してタイトル画面に戻る。
         * スコアは保存されない（途中で戻ったため）。 */
        if (CheckCollisionPointRec(pos, btnTitle))
        {
            game.screen = SCREEN_TITLE; /* タイトル画面に遷移 */
            return;
        }
    }
}


/* ==========================================================================
 * カウントダウンの更新処理
 * ==========================================================================
 * ポーズからの復帰時に 3 → 2 → 1 を表示するカウントダウン。
 * SCREEN_COUNTDOWN の間、毎フレーム呼ばれる。
 *
 * 【なぜカウントダウンが必要？】
 * ポーズ解除と同時にゲームが再開すると、プレイヤーが
 * 準備できていない状態で的が出現してしまう。
 * 3秒のカウントダウンで心構えの時間を与える。
 * ========================================================================== */

void UpdateCountdown(float dt)
{
    /* -----------------------------------------------------------
     * タイマーを減算
     * -----------------------------------------------------------
     * COUNTDOWN_INTERVAL（1.0秒）ごとに数字が変わる。 */
    game.countdownTimer -= dt;

    /* -----------------------------------------------------------
     * タイマーが0以下になったら次の数字へ
     * ----------------------------------------------------------- */
    if (game.countdownTimer <= 0.0f)
    {
        game.countdownNumber--; /* 3→2→1→0 と減る */

        if (game.countdownNumber <= 0)
        {
            /* カウントダウン完了 → ゲーム再開 */
            game.screen = SCREEN_PLAYING;

            /* BGM音量を通常に戻す
             * ポーズ時に BGM_VOLUME_PAUSE に下げていたのを
             * BGM_VOLUME_NORMAL に復元する。 */
            int b; /* ループカウンタ */
            for (b = 0; b < BGM_COUNT; b++)
            {
                if (bgmLoaded[b])
                {
                    SetMusicVolume(bgm[b], BGM_VOLUME_NORMAL);
                }
            }
        }
        else
        {
            /* まだカウントダウン中 → タイマーをリセット
             * 次の数字の表示を開始する。 */
            game.countdownTimer = COUNTDOWN_INTERVAL;
        }
    }
}


