/* ==========================================================================
 * スコアの保存
 * ==========================================================================
 * scores構造体の内容をファイル（ネイティブ）または
 * localStorage（Emscripten / WebAssembly）に書き込む。
 *
 * 【保存タイミング】
 * ゲームオーバー時に UpdatePlaying() から呼ばれる。
 *
 * 【保存形式】
 * ネイティブ: バイナリ形式。ScoreData構造体をそのまま書き出す。
 *   利点: 実装が簡単、サイズが小さい。
 *   欠点: エンディアンやパディングの違いで移植性が低い。
 *         ただしこのゲームではスコアの互換性は重要でないので問題なし。
 *
 * Emscripten: localStorage のキーにJSON風に個別に保存。
 *   localStorage はブラウザのローカルストレージ。
 *   ファイルシステムが使えないWebASMでの代替手段。
 * ========================================================================== */

void SaveScores(void)
{
#ifdef __EMSCRIPTEN__
    /* -----------------------------------------------------------
     * Emscripten版: localStorage に保存
     * -----------------------------------------------------------
     * EM_ASM() マクロでJavaScriptコードを直接実行する。
     * C言語の値を $0, $1, ... で参照できる。
     *
     * 各モードのTOP5スコアを個別のキーで保存する。
     * キー形式: "sataro_ta_0" 〜 "sataro_ta_4" （タイムアタック）
     *           "sataro_sv_0" 〜 "sataro_sv_4" （サバイバル）
     *           "sataro_mr_0" 〜 "sataro_mr_4" （マラソン）
     *
     * 【なぜ個別キーなのか？】
     * JSON.stringify 等を使えばまとめて保存できるが、
     * 1つのキーに構造体全体を入れるのは保守性が低い。
     * 個別キーなら部分的な読み書きも可能。 */
    int i; /* ループカウンタ */
    for (i = 0; i < MAX_RANKINGS; i++)
    {
        /* タイムアタックのスコアを保存 */
        EM_ASM({
            localStorage.setItem("sataro_ta_" + $0, $1);
        }, i, scores.timeattack[i]);

        /* サバイバルのスコアを保存 */
        EM_ASM({
            localStorage.setItem("sataro_sv_" + $0, $1);
        }, i, scores.survival[i]);

        /* マラソンのスコアを保存 */
        EM_ASM({
            localStorage.setItem("sataro_mr_" + $0, $1);
        }, i, scores.marathon[i]);
    }
#else
    /* -----------------------------------------------------------
     * ネイティブ版: バイナリファイルに保存
     * -----------------------------------------------------------
     * fopen() → fwrite() → fclose() の標準的なファイル書き込み。
     *
     * "wb" = Write Binary（バイナリ書き込みモード）
     * テキストモード ("w") だと改行コードが変換される可能性があるため、
     * 構造体データの保存にはバイナリモードを使う。
     *
     * fwrite() の引数:
     *   &scores       : 書き込むデータのアドレス
     *   sizeof(scores): 書き込むバイト数
     *   1             : 1個のデータを書く
     *   fp            : ファイルポインタ
     *
     * 【エラー処理について】
     * fopen() が NULL を返した場合、ファイルを作成できなかった。
     * ディスク容量不足や権限の問題が考えられる。
     * ここではエラーを無視して処理を続行する（ゲームは動き続ける）。 */
    FILE *fp = fopen("scores.dat", "wb");
    if (fp != NULL)
    {
        fwrite(&scores, sizeof(ScoreData), 1, fp);
        fclose(fp); /* ファイルを閉じる（書き込みをフラッシュ） */
    }
#endif
}


/* ==========================================================================
 * スコアの読み込み
 * ==========================================================================
 * ファイル（ネイティブ）またはlocalStorage（Emscripten）から
 * スコアデータを読み込み、scores構造体に格納する。
 *
 * 【呼び出しタイミング】
 * ゲーム起動時（main.c の初期化処理）に1回だけ呼ばれる。
 *
 * 【データがない場合の挙動】
 * 初回起動時はファイル/localStorageが存在しない。
 * その場合は scores を0で初期化する（ランキングが空の状態）。
 * ========================================================================== */

void LoadScores(void)
{
    /* -----------------------------------------------------------
     * まず全スコアを0で初期化
     * -----------------------------------------------------------
     * memset で構造体全体を 0 埋めする。
     * ファイルが読めなかった場合のフォールバック。
     *
     * 【memset の引数】
     * &scores : 初期化するメモリの先頭アドレス
     * 0       : 埋める値（0 = ゼロクリア）
     * sizeof  : 初期化するバイト数 */
    memset(&scores, 0, sizeof(ScoreData));

#ifdef __EMSCRIPTEN__
    /* -----------------------------------------------------------
     * Emscripten版: localStorage から読み込み
     * -----------------------------------------------------------
     * EM_ASM_INT() はJavaScriptの実行結果をintで受け取れるマクロ。
     * localStorage.getItem() で値を取得し、parseInt で整数に変換。
     * キーが存在しない場合は NaN になるので、|| 0 でデフォルト0にする。 */
    int i; /* ループカウンタ */
    for (i = 0; i < MAX_RANKINGS; i++)
    {
        /* タイムアタックのスコアを読み込み */
        scores.timeattack[i] = EM_ASM_INT({
            return parseInt(localStorage.getItem("sataro_ta_" + $0)) || 0;
        }, i);

        /* サバイバルのスコアを読み込み */
        scores.survival[i] = EM_ASM_INT({
            return parseInt(localStorage.getItem("sataro_sv_" + $0)) || 0;
        }, i);

        /* マラソンのスコアを読み込み */
        scores.marathon[i] = EM_ASM_INT({
            return parseInt(localStorage.getItem("sataro_mr_" + $0)) || 0;
        }, i);
    }
#else
    /* -----------------------------------------------------------
     * ネイティブ版: バイナリファイルから読み込み
     * -----------------------------------------------------------
     * "rb" = Read Binary（バイナリ読み込みモード）
     *
     * fread() の引数:
     *   &scores       : 読み込み先のアドレス
     *   sizeof(scores): 読み込むバイト数
     *   1             : 1個のデータを読む
     *   fp            : ファイルポインタ
     *
     * ファイルが存在しない場合は fopen() が NULL を返す。
     * その場合は何もせず、先ほど memset で初期化した0の値が残る。 */
    FILE *fp = fopen("scores.dat", "rb");
    if (fp != NULL)
    {
        fread(&scores, sizeof(ScoreData), 1, fp);
        fclose(fp); /* ファイルを閉じる */
    }
    /* fp == NULL の場合: ファイルが存在しない（初回起動）
     * → memset で初期化済みの0が使われるので問題なし。 */
#endif
}


/* ==========================================================================
 * スコアのランキング登録
 * ==========================================================================
 * 今回のゲーム結果をランキング配列に挿入する。
 * 上位5件（MAX_RANKINGS = 5）に入った場合のみ登録される。
 *
 * 【ソート順序】
 * タイムアタック: 昇順（時間が短いほど良い → 小さい値が上位）
 * サバイバル    : 降順（枚数が多いほど良い → 大きい値が上位）
 * マラソン      : 降順（生存時間が長いほど良い → 大きい値が上位）
 *
 * 【挿入ソートのアルゴリズム】
 * 1. 配列を先頭から走査し、新しい値が入るべき位置を見つける
 * 2. その位置以降のデータを1つずつ後ろにずらす
 * 3. 空いた位置に新しい値を挿入する
 * ※最後の要素は押し出されて消える（TOP5からはみ出す）
 *
 * 戻り値: true = ランキング入り（新記録！）、false = ランク外
 * ========================================================================== */

bool RegisterScore(GameMode mode, int value)
{
    /* -----------------------------------------------------------
     * モードに応じたランキング配列を選択
     * -----------------------------------------------------------
     * ポインタを使って、モードに応じた配列を切り替える。
     * こうすることで、以降の挿入処理をモードごとに書く必要がなくなる。 */
    int *ranking = NULL;    /* ランキング配列へのポインタ */
    bool ascending = false; /* true=昇順（小さいほど上位）, false=降順 */

    switch (mode)
    {
        case MODE_TIMEATTACK:
            ranking = scores.timeattack;
            ascending = true;   /* タイムは短いほど良い → 昇順 */
            break;
        case MODE_SURVIVAL:
            ranking = scores.survival;
            ascending = false;  /* 枚数は多いほど良い → 降順 */
            break;
        case MODE_MARATHON:
            ranking = scores.marathon;
            ascending = false;  /* 生存時間は長いほど良い → 降順 */
            break;
        default:
            return false; /* 不正なモード（通常は到達しない） */
    }

    /* -----------------------------------------------------------
     * 挿入位置を探す
     * -----------------------------------------------------------
     * 配列を先頭から走査し、新しい値が入るべき位置を見つける。
     *
     * 昇順の場合: 値が 0（未登録）または新しい値より大きい位置
     * 降順の場合: 値が 0（未登録）または新しい値より小さい位置
     *
     * 【0の扱い】
     * ranking[i] == 0 はまだスコアが登録されていないスロット。
     * 昇順（タイムアタック）では0秒はありえないので、0は「空き」を意味する。
     * 降順（サバイバル/マラソン）でも0枚/0秒はありえないので同様。 */
    int insertPos = -1; /* 挿入位置（見つからなければ -1 のまま） */
    int i; /* ループカウンタ */

    for (i = 0; i < MAX_RANKINGS; i++)
    {
        if (ascending)
        {
            /* 昇順: まだ未登録のスロット、または自分より遅いタイムの位置 */
            if (ranking[i] == 0 || value < ranking[i])
            {
                insertPos = i;
                break; /* 最初に見つかった位置で確定 */
            }
        }
        else
        {
            /* 降順: まだ未登録のスロット、または自分より少ないスコアの位置 */
            if (ranking[i] == 0 || value > ranking[i])
            {
                insertPos = i;
                break;
            }
        }
    }

    /* -----------------------------------------------------------
     * 挿入位置が見つからなかった場合 → ランク外
     * -----------------------------------------------------------
     * 全5スロットが埋まっていて、新しい値がどのスロットよりも
     * 悪い場合はランクインできない。 */
    if (insertPos == -1)
    {
        return false; /* ランク外 — 新記録ではない */
    }

    /* -----------------------------------------------------------
     * データを後ろにずらして挿入スペースを作る
     * -----------------------------------------------------------
     * 挿入位置以降のデータを1つずつ後ろにシフトする。
     * 最後の要素（ranking[MAX_RANKINGS-1]）は押し出されて消える。
     *
     * 【逆順ループの理由】
     * 後ろからコピーしないと、前のデータで次のデータが上書きされてしまう。
     * 例: [A, B, C, _, _] に位置1で挿入する場合
     *   正しい: [A, _, B, C, _] → 逆順（i=3→2→1）でシフト
     *   間違い: [A, B, B, B, _] → 順方向だとBで全部上書きされる */
    for (i = MAX_RANKINGS - 1; i > insertPos; i--)
    {
        ranking[i] = ranking[i - 1]; /* 1つ後ろにコピー */
    }

    /* -----------------------------------------------------------
     * 新しいスコアを挿入
     * ----------------------------------------------------------- */
    ranking[insertPos] = value;

    /* -----------------------------------------------------------
     * ランクイン成功 → 新記録！
     * -----------------------------------------------------------
     * true を返すことで、リザルト画面に「NEW RECORD!」が表示される。 */
    return true;
}
