/* ==========================================================================
 * ゲーム初期化
 * ==========================================================================
 * ゲーム開始時に呼ばれ、全ての状態をリセットする。
 * タイトル画面でモードを選択したとき、
 * またはポーズ中に「リトライ」を選んだときに呼ばれる。
 * ========================================================================== */

void InitGame(GameMode mode)
{
    /* -----------------------------------------------------------
     * スコア・タイマー・ステージのリセット
     * -----------------------------------------------------------
     * すべて初期値に戻す。前回のプレイデータが残っていると
     * 次のゲームに影響してしまうため、必ず全項目をリセットする。 */
    game.score = 0;              /* 撃ち抜き枚数を0にリセット */
    game.elapsedTime = 0.0f;     /* 経過時間を0秒にリセット */
    game.stage = 1;              /* ステージ1から開始 */
    game.isGameOver = false;     /* ゲームオーバーフラグを解除 */
    game.isNewRecord = false;    /* 新記録フラグを解除 */
    game.isTimedOut = false;     /* タイムアウトフラグを解除 */

    /* -----------------------------------------------------------
     * ゲームモードの設定
     * -----------------------------------------------------------
     * 引数で受け取ったモードを game構造体に保存する。
     * 以降の処理では game.mode を参照してモード別の分岐を行う。 */
    game.mode = mode;

    /* -----------------------------------------------------------
     * 画面状態をプレイ中に設定
     * -----------------------------------------------------------
     * SCREEN_PLAYING に設定することで、メインループの switch文が
     * UpdatePlaying() を呼び出すようになる。 */
    game.screen = SCREEN_PLAYING;

    /* -----------------------------------------------------------
     * エフェクト用タイマーのリセット
     * -----------------------------------------------------------
     * freezeTimer: ミス後の操作不能時間。0以下なら操作可能。
     * flashTimer : ミス後の白フラッシュ時間。0以下なら表示しない。
     * 前回のゲーム終了時に中途半端な値が残っている可能性があるので
     * 必ず 0 にリセットする。 */
    game.freezeTimer = 0.0f;
    game.flashTimer = 0.0f;

    /* -----------------------------------------------------------
     * マラソンモード専用の初期化
     * -----------------------------------------------------------
     * マラソンモードではゲージが時間経過で減少していく。
     * ゲージが0になるとゲームオーバー。
     * gaugeMax   : ゲージの上限値。ステージが進むほど短くなる。
     * gaugeValue : ゲージの現在値。初期状態では満タン。
     * gaugeDecaySpeed : ゲージの毎秒減少量。時間経過で加速する。
     *
     * 他のモードでもこれらの変数は存在するが、参照されないため
     * 初期化しても無害。可読性のため、モード判定なしで初期化する。 */
    game.gaugeMax = GetMarathonGaugeMax(1);  /* ステージ1 → 16.0 秒 */
    game.gaugeValue = game.gaugeMax;          /* 初期値は満タン */
    game.gaugeDecaySpeed = MARATHON_INITIAL_DECAY; /* 初期減少速度 = 1.0 */

    /* -----------------------------------------------------------
     * 全行の的を初期生成
     * -----------------------------------------------------------
     * 6行 × 3列 = 18個 の的を一斉に生成する。
     * これによりゲーム開始時から画面に的が表示される。 */
    InitAllTargetRows();

    /* -----------------------------------------------------------
     * 乱数シードの初期化
     * -----------------------------------------------------------
     * srand() に time(NULL)（現在の秒数）を渡すことで、
     * ゲーム開始のたびに異なる乱数列が生成される。
     * これにより毎回違う正解レーンの配置になる。
     *
     * 【注意】
     * srand() を InitAllTargetRows() の後に呼んでいるのは、
     * InitAllTargetRows() 内で rand() を使うため、
     * 初回は同じパターンになる可能性があるが、
     * ゲームプレイに支障はない（むしろデバッグ時に便利）。
     * 本来は InitAllTargetRows() の前に呼ぶのが理想的。
     * ここでは仕様に従い、この順序で実装する。 */
    srand((unsigned int)time(NULL));
}


/* ==========================================================================
 * 的（ターゲット）の生成
 * ==========================================================================
 * 指定した行に3つの的を生成する。
 * 3つのうち1つが「正解」（画像を表示）、残り2つが「空欄」（×マーク）。
 * マラソンモードでは5%の確率で正解が2つ同時に出現する。
 * ========================================================================== */

void GenerateTargetRow(int row)
{
    /* -----------------------------------------------------------
     * 正解レーンをランダムに1つ選ぶ
     * -----------------------------------------------------------
     * rand() % LANE_COUNT → 0, 1, 2 のいずれかの値を返す。
     * この値のレーンに正解の的を配置する。
     *
     * 【rand() の注意点】
     * rand() は擬似乱数なので、srand() で初期化しないと
     * 毎回同じ値が返る。InitGame() で srand() を呼んでいる。 */
    int correctLane = rand() % LANE_COUNT;

    /* -----------------------------------------------------------
     * 全3レーンの的を設定する
     * -----------------------------------------------------------
     * まず全レーンを「空欄（不正解）」として初期化し、
     * その後で正解レーンだけ上書きする戦略。
     * これによりコードがシンプルになる。 */
    int i; /* ループカウンタ（C99以前との互換性のためループ外で宣言） */
    for (i = 0; i < LANE_COUNT; i++)
    {
        /* --- 共通の初期値を設定 --- */
        game.targets[row][i].lane = i;          /* レーン番号を設定 */
        game.targets[row][i].row = row;          /* 行番号を設定 */
        game.targets[row][i].isActive = true;    /* この的は有効（画面に存在する） */
        game.targets[row][i].isCorrect = false;  /* デフォルトは不正解（空欄） */
        game.targets[row][i].imageIndex = -1;    /* -1 = 画像なし（×マークを描画） */
    }

    /* -----------------------------------------------------------
     * 正解レーンの設定
     * -----------------------------------------------------------
     * isCorrect = true にすることで、render.c が画像を描画する。
     * imageIndex はステージ番号に対応する画像を指定する。
     * game.stage は 1始まり、textures[] は 0始まりなので -1 する。
     *
     * 【imageIndex の意味】
     * textures[imageIndex] の画像がこの的に描画される。
     * ステージ1ならtextures[0]、ステージ16ならtextures[15]。 */
    game.targets[row][correctLane].isCorrect = true;
    game.targets[row][correctLane].imageIndex = game.stage - 1;

    /* -----------------------------------------------------------
     * マラソンモード特殊処理: ダブル正解（5%の確率）
     * -----------------------------------------------------------
     * マラソンモードでは、稀に正解が2つ同時に出現する。
     * これはプレイヤーへのボーナス（どちらを撃っても正解）。
     *
     * 【確率の仕組み】
     * rand() / (float)RAND_MAX → 0.0 ～ 1.0 の一様乱数を生成。
     * この値が MARATHON_DUAL_CHANCE (0.05) 未満なら発動。
     * つまり 5% の確率でダブル正解が発生する。
     *
     * 【2つ目の正解レーンの選び方】
     * 最初の正解レーンと重複しないように、
     * (correctLane + 1 + rand() % 2) % LANE_COUNT で
     * 残り2つのレーンからランダムに1つを選ぶ。
     * 例: correctLane=0 → 候補は (0+1+0)%3=1 または (0+1+1)%3=2 */
    if (game.mode == MODE_MARATHON)
    {
        /* 0.0 ～ 1.0 の一様乱数を生成 */
        float dualRoll = (float)rand() / (float)RAND_MAX;

        if (dualRoll < MARATHON_DUAL_CHANCE)
        {
            /* 2つ目の正解レーンを、最初の正解と被らないように選ぶ */
            int secondLane = (correctLane + 1 + rand() % 2) % LANE_COUNT;

            /* 2つ目のレーンも正解に設定（同じ画像を使用） */
            game.targets[row][secondLane].isCorrect = true;
            game.targets[row][secondLane].imageIndex = game.stage - 1;
        }
    }
}


/* ==========================================================================
 * 全行の的を一括初期化
 * ==========================================================================
 * ゲーム開始時に呼ばれる。
 * 全6行分の的を GenerateTargetRow() で生成する。
 * ========================================================================== */

void InitAllTargetRows(void)
{
    /* -----------------------------------------------------------
     * 全行を順番に生成
     * -----------------------------------------------------------
     * row=0（最手前）から row=MAX_VISIBLE_ROWS-1（最奥=5）まで、
     * 各行に3つの的を生成する。
     *
     * 【なぜ手前から生成するのか？】
     * GenerateTargetRow() 内で game.stage を参照して
     * imageIndex を設定するため、行の順番は実は関係ない。
     * ただし可読性のため、手前から奥に向かって生成する。 */
    int row; /* ループカウンタ */
    for (row = 0; row < MAX_VISIBLE_ROWS; row++)
    {
        GenerateTargetRow(row); /* row行目に的を3つ生成 */
    }
}


/* ==========================================================================
 * 的のスライド（前方シフト）
 * ==========================================================================
 * 正解を撃ち抜いたとき呼ばれる。
 * 最手前（row=0）の的を消去し、後ろの的を1行ずつ手前にずらし、
 * 最奥（row=MAX_VISIBLE_ROWS-1）に新しい的を生成する。
 *
 * 【ベルトコンベアのイメージ】
 * 前: [A][B][C][D][E][F]
 * 後: [B][C][D][E][F][新]
 *
 * 行番号は位置に対応するので、ずらした後に各的の .row を更新する。
 * ========================================================================== */

void SlideTargetsForward(void)
{
    int row;  /* 外側ループカウンタ: 行番号 */
    int lane; /* 内側ループカウンタ: レーン番号 */

    /* -----------------------------------------------------------
     * 行を1つずつ前にシフト
     * -----------------------------------------------------------
     * row=0 に row=1 のデータをコピー、
     * row=1 に row=2 のデータをコピー、
     * ... と繰り返す。
     *
     * 【シフトの方向に注意】
     * row=0 から順に上書きすることで、データが正しく前方に移動する。
     * 逆順（後ろから）だとデータが壊れてしまう。 */
    for (row = 0; row < MAX_VISIBLE_ROWS - 1; row++)
    {
        for (lane = 0; lane < LANE_COUNT; lane++)
        {
            /* 次の行のデータを現在の行にコピー */
            game.targets[row][lane] = game.targets[row + 1][lane];

            /* -----------------------------------------------------------
             * コピー後に行番号を更新
             * -----------------------------------------------------------
             * コピー元の .row は row+1 のままなので、
             * 新しい位置 row に合わせて更新する必要がある。
             * これを忘れると GetTargetRect() で間違った位置に描画される。 */
            game.targets[row][lane].row = row;
        }
    }

    /* -----------------------------------------------------------
     * 最後尾の行に新しい的を生成
     * -----------------------------------------------------------
     * シフトにより最奥の行が空いたので、新しい的を生成する。
     * GenerateTargetRow() は .row フィールドも正しく設定する。 */
    GenerateTargetRow(MAX_VISIBLE_ROWS - 1);
}


/* ==========================================================================
 * 的のサイズ計算
 * ==========================================================================
 * 疑似3D表現のため、手前の的ほど大きく、奥の的ほど小さく描画する。
 * 線形補間（リニアインターポレーション = lerp）で中間サイズを計算。
 *
 * 【線形補間の仕組み】
 * t = 0.0 → SIZE_FRONT（最大サイズ）
 * t = 1.0 → SIZE_BACK （最小サイズ）
 * t が 0.0〜1.0 の間の値なら、その比率に応じた中間サイズになる。
 *
 * 式: result = FRONT + (BACK - FRONT) * t
 * ※BACK < FRONT なので (BACK - FRONT) は負の値。
 *   つまり t が大きくなるほど result は小さくなる。
 * ========================================================================== */

float GetTargetSize(int row)
{
    /* -----------------------------------------------------------
     * 補間係数 t を計算
     * -----------------------------------------------------------
     * row=0 → t=0.0（最手前、最大サイズ）
     * row=MAX_VISIBLE_ROWS-1 → t=1.0（最奥、最小サイズ）
     *
     * (float) キャストが必要。int 同士の割り算だと小数点以下が
     * 切り捨てられてしまい、t は 0 か 1 しか取らなくなる。 */
    float t = (float)row / (float)(MAX_VISIBLE_ROWS - 1);

    /* -----------------------------------------------------------
     * 線形補間でサイズを計算して返す
     * -----------------------------------------------------------
     * TARGET_SIZE_FRONT = 120px, TARGET_SIZE_BACK = 40px のとき:
     * row=0 → 120 + (40-120)*0.0 = 120.0（最大）
     * row=2 → 120 + (40-120)*0.4 = 88.0（中間）
     * row=5 → 120 + (40-120)*1.0 = 40.0（最小） */
    return (float)TARGET_SIZE_FRONT
         + ((float)TARGET_SIZE_BACK - (float)TARGET_SIZE_FRONT) * t;
}


/* ==========================================================================
 * 的の描画矩形（バウンディングボックス）の計算
 * ==========================================================================
 * 指定した行・レーンの的がスクリーン上のどの位置に描画されるかを
 * Rectangle（x, y, width, height）として返す。
 *
 * この矩形は2つの目的で使われる:
 * 1. render.c での描画位置・サイズの決定
 * 2. HandleTargetTap() での当たり判定（衝突判定）
 *
 * 【疑似3Dパース処理の概要】
 * ・手前の行（row=0）は大きく、レーン間隔も広い
 * ・奥の行（row=5）は小さく、レーン間隔も狭い
 * ・Y座標は下から上に向かって積み上げ式に計算
 * ========================================================================== */

Rectangle GetTargetRect(int row, int lane)
{
    /* -----------------------------------------------------------
     * この行の的のサイズを取得
     * -----------------------------------------------------------
     * GetTargetSize() で線形補間されたサイズを得る。
     * 正方形の的なので width = height = size。 */
    float size = GetTargetSize(row);

    /* -----------------------------------------------------------
     * プレイエリアの横幅を計算
     * -----------------------------------------------------------
     * PLAY_AREA_RIGHT - PLAY_AREA_LEFT = 425 - 25 = 400 ピクセル。
     * この幅の中に3つの的を並べる。 */
    float playAreaWidth = (float)(PLAY_AREA_RIGHT - PLAY_AREA_LEFT);

    /* -----------------------------------------------------------
     * パース（遠近法）によるレーン幅の計算
     * -----------------------------------------------------------
     * 【バグ修正：的が画面外にはみ出す問題の解決】
     * 修正前は playAreaWidth（プレイエリアの全幅）を直接ベースに計算していたため、
     * laneWidth が大きくなりすぎ、3レーン分描画すると左右に大きくはみ出していました。
     *
     * 正しくは、まず playAreaWidth を LANE_COUNT（3レーン）で割って
     * 「1レーン分の基本幅」を求め、そこに遠近法の比率を掛ける必要があります。
     *
     * 修正後の式:
     * laneWidth = (playAreaWidth / LANE_COUNT) * (size / TARGET_SIZE_FRONT)
     *
     * これにより、手前の行（size=TARGET_SIZE_FRONT）では基本幅そのままになり、
     * 奥の行（sizeが小さい）では比例してレーン幅も小さくなります。
     * 
     * 例: playAreaWidth=400, LANE_COUNT=3, TARGET_SIZE_FRONT=120 の場合
     * 手前（size=120）→ laneWidth = (400/3) * (120/120) ≈ 133.3
     * 最奥（size=40） → laneWidth = (400/3) * (40/120)  ≈ 44.4 */
    float laneWidth = (playAreaWidth / (float)LANE_COUNT) * (size / (float)TARGET_SIZE_FRONT);

    /* -----------------------------------------------------------
     * 全レーンの合計幅と、開始X座標を計算
     * -----------------------------------------------------------
     * totalWidth = 3レーン分の合計幅
     * startX = 合計幅をプレイエリア中央に配置するための開始X座標
     *
     * (playAreaWidth - totalWidth) / 2 で左右の余白が均等になる。 */
    float totalWidth = laneWidth * (float)LANE_COUNT;
    float startX = (float)PLAY_AREA_LEFT + (playAreaWidth - totalWidth) / 2.0f;

    /* -----------------------------------------------------------
     * X座標の計算
     * -----------------------------------------------------------
     * 各レーンの的は、そのレーンの中央に配置する。
     * lane * laneWidth で各レーンの左端位置を求め、
     * (laneWidth - size) / 2 で的をレーン中央に寄せる。
     *
     * 例（手前・中央レーン）:
     * startX=25, laneWidth≈133, size=120, lane=1
     * x = 25 + 1*133 + (133-120)/2 = 25 + 133 + 6.5 = 164.5 */
    float x = startX + (float)lane * laneWidth + (laneWidth - size) / 2.0f;

    /* -----------------------------------------------------------
     * Y座標の計算（下から積み上げ方式）
     * -----------------------------------------------------------
     * 最手前（row=0）の底辺を PLAY_AREA_BOTTOM に合わせ、
     * そこから上方向に各行を積み上げていく。
     *
     * 【重なり（オーバーラップ）の仕組み】
     * 行と行の間にはROW_OVERLAP_RATIO分の重なりがある。
     * 重なりがないと行間に隙間ができてしまい不自然。
     * 0.35（35%重なり）だと自然な奥行き感が出る。
     *
     * 各行のY方向の「消費ピクセル数」:
     *   consumedHeight = その行のsize × (1.0 - ROW_OVERLAP_RATIO)
     *
     * row=0 の上端: PLAY_AREA_BOTTOM - size_of_row0
     * row=1 の上端: row=0の上端 - consumedHeight_of_row0 の残り
     * ...と積み上げていく。
     *
     * 【イテレーティブ計算の理由】
     * 各行のサイズが異なるため、閉じた式で計算するのは複雑。
     * ループで1行ずつ Y オフセットを加算していくのがシンプルで確実。 */
    float y = (float)PLAY_AREA_BOTTOM; /* まず底辺からスタート */

    /* row=0 の場合: y = PLAY_AREA_BOTTOM - size（底辺にぴったり） */
    /* row>0 の場合: 手前の行の分だけ上にずらす */
    int r; /* ループカウンタ: 手前から順に処理 */
    for (r = 0; r < row; r++)
    {
        /* r行目の的のサイズを取得 */
        float rowSize = GetTargetSize(r);

        /* r行目が「消費する」Y方向のピクセル数を計算
         * (1.0 - ROW_OVERLAP_RATIO) = 重なりを差し引いた実質的な高さ */
        y -= rowSize * (1.0f - ROW_OVERLAP_RATIO);
    }

    /* 最後に、現在の行の的自体の高さ分を引いて上端Y座標にする
     * （y は今「この行の底辺」の位置なので、sizeを引くと上端になる） */
    y -= size;

    /* -----------------------------------------------------------
     * 計算結果をRectangleとして返す
     * -----------------------------------------------------------
     * Rectangle = { x, y, width, height }
     * 的は正方形なので width = height = size */
    return (Rectangle){ x, y, size, size };
}


/* ==========================================================================
 * タップ判定
 * ==========================================================================
 * プレイヤーがクリック/タップした位置を受け取り、
 * 最手前の行（row=0）のどの的に当たったかを判定する。
 *
 * 【なぜ row=0 だけチェックするのか？】
 * ゲームのルール上、プレイヤーは常に「最も手前の的」を
 * 処理する必要がある。奥の的は見えているだけで触れない。
 * ========================================================================== */

TapResult HandleTargetTap(Vector2 pos)
{
    /* -----------------------------------------------------------
     * フリーズ中はタップを無視
     * -----------------------------------------------------------
     * ミス後しばらくは操作不能（ペナルティ）。
     * freezeTimer が0より大きい間は全てのタップを無視する。 */
    if (game.freezeTimer > 0.0f)
    {
        return TAP_NONE; /* フリーズ中 → 何も起きない */
    }

    /* -----------------------------------------------------------
     * 最手前の行（row=0）の各レーンを判定
     * -----------------------------------------------------------
     * 左(0)、中央(1)、右(2) の順にチェックする。
     * 最初にヒットしたレーンで処理を確定する。
     *
     * 【CheckCollisionPointRec() とは？】
     * Raylibの組み込み関数。点（pos）が矩形（rect）の
     * 内部にあれば true を返す。当たり判定に便利。 */
    int lane; /* ループカウンタ */
    for (lane = 0; lane < LANE_COUNT; lane++)
    {
        /* この的の描画矩形を取得 */
        Rectangle rect = GetTargetRect(0, lane);

        /* タップ位置がこの的の矩形内にあるか判定 */
        if (CheckCollisionPointRec(pos, rect))
        {
            /* --- タップが的の上にある場合 --- */
            if (game.targets[0][lane].isCorrect)
            {
                /* 正解の的を撃ち抜いた！ */
                OnTargetHit();   /* スコア加算・ステージ更新など */
                return TAP_HIT;  /* 呼び出し元にヒットを通知 */
            }
            else
            {
                /* 空欄の的をタップしてしまった（ミス） */
                OnTargetMiss();  /* フリーズ・フラッシュなど */
                return TAP_MISS; /* 呼び出し元にミスを通知 */
            }
        }
    }

    /* -----------------------------------------------------------
     * どの的にも当たらなかった場合
     * -----------------------------------------------------------
     * 的と的の隙間をタップした場合や、プレイエリア外の場合。
     * ペナルティなし。 */
    return TAP_NONE;
}


/* ==========================================================================
 * 内部ヘルパー: ヒット時の処理
 * ==========================================================================
 * 正解の的を撃ち抜いたときに呼ばれる。
 * モードに関係なく共通の処理を行い、その後モード別の処理を行う。
 *
 * static なので logic.c 内からのみ呼び出し可能。
 * ========================================================================== */

static void OnTargetHit(void)
{
    /* -----------------------------------------------------------
     * スコア加算
     * -----------------------------------------------------------
     * 正解を1つ撃ち抜くごとに+1。シンプルなカウント方式。 */
    game.score++;

    /* -----------------------------------------------------------
     * ステージ更新
     * -----------------------------------------------------------
     * スコアが閾値に達したら次のステージに進む。
     * GetCurrentStage() がスコアから適切なステージ番号を返す。 */
    game.stage = GetCurrentStage(game.score);

    /* -----------------------------------------------------------
     * 的をスライド
     * -----------------------------------------------------------
     * 撃ち抜いた行（row=0）を消去し、後続の行を前に詰める。
     * 最奥に新しい的が自動生成される。 */
    SlideTargetsForward();

    /* -----------------------------------------------------------
     * モード別のヒット後処理
     * ----------------------------------------------------------- */
    if (game.mode == MODE_MARATHON)
    {
        /* 【マラソンモード】
         * ゲージ上限をステージに合わせて更新。
         * ステージが進むほど gaugeMax が小さくなり、
         * ゲージの持ち時間が短くなる（難易度上昇）。
         *
         * ヒット時にゲージが満タンに回復するので、
         * 撃ち抜き続ければゲージは減らない。
         * ミスせず素早く撃つことが重要。 */
        game.gaugeMax = GetMarathonGaugeMax(game.stage);
        game.gaugeValue = game.gaugeMax; /* ゲージ全回復！ */
    }
    else if (game.mode == MODE_TIMEATTACK)
    {
        /* 【タイムアタックモード】
         * 目標枚数（TIMEATTACK_GOAL = 50）に達したらゲームクリア。
         * isGameOver を true にするとリザルト画面に遷移する。 */
        if (game.score >= TIMEATTACK_GOAL)
        {
            game.isGameOver = true; /* ゲームクリア！ */
        }
    }
    /* 【サバイバルモード】
     * ヒット時の特別な処理はない。ひたすら撃ち続ける。 */
}


/* ==========================================================================
 * 内部ヘルパー: ミス時の処理
 * ==========================================================================
 * 空欄の的をタップしてしまったときに呼ばれる。
 * ペナルティとして操作不能時間と白フラッシュを設定する。
 *
 * サバイバルモードでは即ゲームオーバー。
 * ========================================================================== */

static void OnTargetMiss(void)
{
    /* -----------------------------------------------------------
     * 操作不能タイマーの設定（全モード共通）
     * -----------------------------------------------------------
     * MISS_FREEZE_TIME（1.0秒）間、タップ入力を無視する。
     * これによりプレイヤーに「ミスした」という感覚を与える。
     * 連打でごまかすことを防止する効果もある。 */
    game.freezeTimer = MISS_FREEZE_TIME;

    /* -----------------------------------------------------------
     * 白フラッシュタイマーの設定（全モード共通）
     * -----------------------------------------------------------
     * MISS_FLASH_TIME（0.15秒）間、画面に白い半透明オーバーレイを表示。
     * 視覚的に「ミスった！」と分かるエフェクト。
     * render.c がこのタイマーを見てフラッシュを描画する。 */
    game.flashTimer = MISS_FLASH_TIME;

    /* -----------------------------------------------------------
     * サバイバルモード: 即ゲームオーバー
     * -----------------------------------------------------------
     * サバイバルモードは「ミスしたら終わり」がルール。
     * 1回でもミスすると即座にゲームオーバーになる。
     * 他のモードではミスしてもフリーズ後に復帰できる。 */
    if (game.mode == MODE_SURVIVAL)
    {
        game.isGameOver = true; /* 即ゲームオーバー！ */
    }
}


/* ==========================================================================
 * ステージ番号の計算
 * ==========================================================================
 * 現在のスコア（撃ち抜き枚数）からステージ番号を決定する。
 * 閾値テーブルを順番にチェックし、スコアがどの範囲にあるかで判断。
 *
 * 例（通常テーブル）:
 *   スコア 0〜2  → ステージ1
 *   スコア 3〜5  → ステージ2
 *   スコア 6〜8  → ステージ3
 *   ...
 *   スコア 88以上 → ステージ16
 * ========================================================================== */

int GetCurrentStage(int score)
{
    /* -----------------------------------------------------------
     * モードに応じた閾値テーブルを選択
     * -----------------------------------------------------------
     * タイムアタックは50枚で完了するため、専用のテーブルを使う。
     * サバイバル・マラソンは共通のテーブル（STAGE_THRESHOLDS）。
     *
     * 【const int* ポインタの意味】
     * 配列の先頭アドレスを指すポインタ。
     * 閾値テーブルの配列をモードに応じて切り替えるために使う。 */
    const int *thresholds;

    if (game.mode == MODE_TIMEATTACK)
    {
        thresholds = TIMEATTACK_STAGE_THRESHOLDS;
    }
    else
    {
        /* サバイバルとマラソンは同じテーブルを共有 */
        thresholds = STAGE_THRESHOLDS;
    }

    /* -----------------------------------------------------------
     * 閾値テーブルを順にチェック
     * -----------------------------------------------------------
     * thresholds[] には TOTAL_STAGES - 1 = 15 個の閾値が入っている。
     * thresholds[i] = ステージ(i+2) に上がるのに必要な累計スコア。
     *
     * スコアが thresholds[i] 未満なら、まだステージ(i+1) に留まる。
     * → ステージ番号 = i + 1 を返す。
     *
     * 例: score=5, thresholds = {3, 6, 9, ...}
     * i=0: score(5) < thresholds[0](3)? → NO
     * i=1: score(5) < thresholds[1](6)? → YES → return 1+1 = 2
     * → ステージ2 */
    int i; /* ループカウンタ */
    for (i = 0; i < TOTAL_STAGES - 1; i++)
    {
        if (score < thresholds[i])
        {
            return i + 1; /* まだこのステージに留まっている */
        }
    }

    /* -----------------------------------------------------------
     * 全ての閾値を超えた場合 → 最終ステージ
     * -----------------------------------------------------------
     * スコアが全ての閾値を超えた場合は、最終ステージ（16）を返す。
     * サバイバル・マラソンでは理論上いくらでもスコアが伸びるので、
     * 最終ステージに達したらそこに留まり続ける。 */
    return TOTAL_STAGES;
}


/* ==========================================================================
 * マラソンモードのゲージ最大値計算
 * ==========================================================================
 * ステージが進むほどゲージの上限が小さくなり、
 * 撃ち抜くまでの猶予時間が短くなる。
 *
 * 式: max(17 - stage, 1)
 *   stage=1  → 16.0 秒（余裕がある）
 *   stage=8  →  9.0 秒（やや厳しい）
 *   stage=16 →  1.0 秒（ほぼ一瞬！）
 *   stage>16 →  1.0 秒（下限クランプ）
 *
 * 【なぜ 17 - stage なのか？】
 * ステージ1で16秒、ステージ16で1秒としたいから。
 * 17 - 1 = 16, 17 - 16 = 1 → ちょうど良い。
 * ========================================================================== */

float GetMarathonGaugeMax(int stage)
{
    /* -----------------------------------------------------------
     * 17 - stage を計算し、最低1.0を保証する
     * -----------------------------------------------------------
     * stage が17以上になることは現仕様では起きないが、
     * 万が一の場合にゲージが0や負にならないよう下限を設ける。
     *
     * 【三項演算子の読み方】
     * 条件 ? 真の値 : 偽の値
     * (17 - stage) > 1 なら (17 - stage)、そうでなければ 1 */
    int value = 17 - stage;                     /* ゲージ最大値の整数部分 */
    return (value > 1) ? (float)value : 1.0f;   /* 最低1.0秒を保証 */
}


/* ==========================================================================
 * プレイ中の毎フレーム更新処理
 * ==========================================================================
 * ゲームプレイ中（SCREEN_PLAYING）に毎フレーム呼ばれる。
 *
 * 行うこと:
 * 1. タイマーの更新（フリーズ、フラッシュ、経過時間）
 * 2. モード別のルール処理（制限時間、ゲージ減少など）
 * 3. プレイヤー入力の処理（タップ判定、ポーズボタン）
 * 4. ゲームオーバー判定と画面遷移
 *
 * 引数 dt はデルタタイム（前フレームからの経過秒数）。
 * 60FPS なら約 0.0167 秒。これを掛け算することで
 * フレームレートに依存しない処理が実現できる。
 * ========================================================================== */

void UpdatePlaying(float dt)
{
    /* -----------------------------------------------------------
     * 1. タイマーの更新
     * ----------------------------------------------------------- */

    /* フリーズタイマーの減算
     * ミス後の操作不能時間を dt ずつ減らしていく。
     * 0以下になったら操作可能に戻る。 */
    if (game.freezeTimer > 0.0f)
    {
        game.freezeTimer -= dt;
    }

    /* フラッシュタイマーの減算
     * 白フラッシュの表示時間を dt ずつ減らしていく。
     * 0以下になったらフラッシュ終了。 */
    if (game.flashTimer > 0.0f)
    {
        game.flashTimer -= dt;
    }

    /* 経過時間の加算
     * ゲーム開始からの総経過時間。
     * タイムアタックのスコアやマラソンの難易度加速に使う。 */
    game.elapsedTime += dt;

    /* -----------------------------------------------------------
     * 2. モード別のルール処理
     * ----------------------------------------------------------- */

    if (game.mode == MODE_TIMEATTACK)
    {
        /* 【タイムアタック】制限時間チェック
         * TIMEATTACK_LIMIT（60秒）を超えたらタイムアウト。
         * 50枚撃ち抜けなかったので記録なしのゲームオーバー。
         *
         * isTimedOut = true にすると、リザルト画面で
         * 「TIME UP」と表示され、ランキングに登録されない。 */
        if (game.elapsedTime >= TIMEATTACK_LIMIT)
        {
            game.isGameOver = true;
            game.isTimedOut = true;
        }
    }
    else if (game.mode == MODE_MARATHON)
    {
        /* 【マラソン】ゲージ減少処理
         * ゲージは時間経過とともに減り続ける。
         * 減少速度は時間とともに加速する（じわじわ厳しくなる）。
         *
         * gaugeDecaySpeed の計算式:
         *   MARATHON_INITIAL_DECAY + elapsedTime * MARATHON_DECAY_ACCEL
         *   = 1.0 + 経過秒数 × 0.008
         *
         * 例: 開始直後 → 1.0/秒、60秒後 → 1.48/秒、120秒後 → 1.96/秒
         *
         * gaugeValue の減算:
         *   gaugeValue -= gaugeDecaySpeed * dt
         *   dtを掛けることでフレームレートに依存しない。 */
        game.gaugeDecaySpeed = MARATHON_INITIAL_DECAY
                             + game.elapsedTime * MARATHON_DECAY_ACCEL;
        game.gaugeValue -= game.gaugeDecaySpeed * dt;

        /* ゲージが0以下になったらゲームオーバー */
        if (game.gaugeValue <= 0.0f)
        {
            game.gaugeValue = 0.0f;   /* 負の値にならないようクランプ */
            game.isGameOver = true;    /* ゲームオーバー！ */
        }
    }
    /* 【サバイバル】
     * 時間ベースの更新処理は特になし。
     * ミス時の即ゲームオーバーは OnTargetMiss() で処理済み。 */

    /* -----------------------------------------------------------
     * 3. プレイヤー入力の処理
     * -----------------------------------------------------------
     * フリーズ中でもポーズボタンは押せるようにするか、
     * フリーズ中は全入力を無視するかはゲームデザイン次第。
     * ここではポーズボタンはフリーズ中でも押せるようにする。 */

    if (IsMouseButtonPressed(MOUSE_BUTTON_LEFT))
    {
        /* マウス/タッチのクリック位置を取得 */
        Vector2 pos = GetMousePosition();

        /* --- ポーズボタンの判定 ---
         * 画面右上にあるポーズボタン（⏸）をタップしたか判定。
         * ポーズボタンの矩形は #define で定義済み。 */
        Rectangle pauseRect = {
            (float)PAUSE_BTN_X,     /* ボタンのX座標（右上寄り） */
            (float)PAUSE_BTN_Y,     /* ボタンのY座標（上寄り） */
            (float)PAUSE_BTN_SIZE,  /* ボタンの幅 */
            (float)PAUSE_BTN_SIZE   /* ボタンの高さ（正方形） */
        };

        if (CheckCollisionPointRec(pos, pauseRect))
        {
            /* ポーズボタンが押された */
            game.screen = SCREEN_PAUSE;   /* ポーズ画面に遷移 */

            /* BGM音量を下げる（ポーズ中は静かめに）
             * bgmLoaded[] で読み込み済みか確認してから操作する。
             * 読み込まれていないBGMに対して SetMusicVolume すると
             * クラッシュする可能性があるため。 */
            int b; /* ループカウンタ */
            for (b = 0; b < BGM_COUNT; b++)
            {
                if (bgmLoaded[b])
                {
                    SetMusicVolume(bgm[b], BGM_VOLUME_PAUSE);
                }
            }
            return; /* ポーズに入ったのでこのフレームの処理はここまで */
        }

        /* --- 的のタップ判定 ---
         * ポーズボタンでなければ、プレイエリア内の的に対して
         * 当たり判定を行う。
         * HandleTargetTap() が内部で OnTargetHit/OnTargetMiss を呼ぶ。 */
        HandleTargetTap(pos);
    }

    /* --- キーボード入力判定 ---
     * パソコン向けの遊びやすさのため、方向キーでも遊べるようにする。
     * 左キー(0:左レーン), 上キー(1:中央レーン), 右キー(2:右レーン) で直接撃ち抜く。 */
    int pressedLane = -1;
    if (IsKeyPressed(KEY_LEFT))       pressedLane = 0;
    else if (IsKeyPressed(KEY_UP))    pressedLane = 1;
    else if (IsKeyPressed(KEY_RIGHT)) pressedLane = 2;

    if (pressedLane != -1 && game.freezeTimer <= 0.0f)
    {
        if (game.targets[0][pressedLane].isCorrect)
        {
            OnTargetHit();   /* 正解を撃ち抜いた */
        }
        else
        {
            OnTargetMiss();  /* 空欄を撃ってしまった */
        }
    }

    /* -----------------------------------------------------------
     * 4. ゲームオーバー判定と画面遷移
     * -----------------------------------------------------------
     * isGameOver が true になったら（どの経路でも）、
     * リザルト画面に遷移し、スコアを登録する。 */
    if (game.isGameOver)
    {
        game.screen = SCREEN_RESULT; /* リザルト画面に遷移 */

        /* --- スコア登録 ---
         * モードに応じたスコア値をランキングに登録する。
         *
         * タイムアタック: 経過時間（ミリ秒）。タイムアウトなら登録しない。
         * サバイバル    : 撃ち抜いた枚数。
         * マラソン      : 生存時間（ミリ秒）。 */
        if (game.mode == MODE_TIMEATTACK)
        {
            if (!game.isTimedOut)
            {
                /* 経過時間を秒→ミリ秒に変換して登録
                 * (int)(elapsedTime * 1000) で小数点以下を切り捨て */
                int timeMs = (int)(game.elapsedTime * 1000.0f);
                game.isNewRecord = RegisterScore(MODE_TIMEATTACK, timeMs);
            }
        }
        else if (game.mode == MODE_SURVIVAL)
        {
            /* サバイバル: 撃ち抜き枚数をそのまま登録 */
            game.isNewRecord = RegisterScore(MODE_SURVIVAL, game.score);
        }
        else if (game.mode == MODE_MARATHON)
        {
            /* マラソン: 生存時間をミリ秒で登録 */
            int timeMs = (int)(game.elapsedTime * 1000.0f);
            game.isNewRecord = RegisterScore(MODE_MARATHON, timeMs);
        }

        /* スコアをファイルに保存（永続化） */
        SaveScores();
    }
}


/* ==========================================================================
 * タイトル画面の更新処理
 * ==========================================================================
 * タイトル画面（SCREEN_TITLE）で毎フレーム呼ばれる。
 *
 * 行うこと:
 * 1. 背景スライドショーの更新（画像の自動切り替えとフェード）
 * 2. モード選択ボタンのクリック判定
 * 3. スコアボタンのクリック判定
 * ========================================================================== */

void UpdateTitle(float dt)
{
    /* -----------------------------------------------------------
     * 1. スライドショーの更新
     * -----------------------------------------------------------
     * タイトル画面の背景に、ゲーム内の的の画像を
     * 自動的にスライドショー表示する演出。
     *
     * slideTimer: 次の画像への切り替えカウントダウン。
     * slideIndex: 現在表示中の画像番号（0〜15）。
     * slideAlpha: フェードアニメーション用の不透明度（0.0〜1.0）。 */

    /* タイマーを dt ずつ減算。0以下になったら次の画像へ。 */
    game.slideTimer -= dt;

    if (game.slideTimer <= 0.0f)
    {
        /* --- 画像を次に切り替え ---
         * slideIndex を +1 し、TOTAL_STAGES（16）で割った余りを取ることで
         * 0 → 1 → 2 → ... → 15 → 0 → 1 ... とループする。
         *
         * 【剰余演算（%）のテクニック】
         * index = (index + 1) % MAX は配列をループさせる定番パターン。
         * MAX を超えたら自動的に 0 に戻る。 */
        game.slideIndex = (game.slideIndex + 1) % TOTAL_STAGES;

        /* 次のスライドの画像番号を先に計算しておく（フェード用） */
        game.slideIndexNext = (game.slideIndex + 1) % TOTAL_STAGES;

        /* タイマーをリセットして次の切り替えまでカウントダウン開始 */
        game.slideTimer = SLIDE_INTERVAL;

        /* フェードアルファを 0（透明）にリセット
         * ここからフェードインが始まる */
        game.slideAlpha = 0.0f;
    }

    /* --- フェードアルファの更新 ---
     * slideAlpha を SLIDE_FADE_SPEED の速度で 1.0 に向かって増加させる。
     * 1.0 に達したらクランプ（上限固定）する。
     *
     * 【フェードの仕組み】
     * render.c では slideAlpha を使って2枚の画像をアルファブレンドする。
     * alpha=0 → 前の画像のみ表示
     * alpha=1 → 次の画像に完全に切り替わった状態 */
    if (game.slideAlpha < 1.0f)
    {
        game.slideAlpha += SLIDE_FADE_SPEED * dt;

        /* 1.0 を超えないようにクランプ */
        if (game.slideAlpha > 1.0f)
        {
            game.slideAlpha = 1.0f;
        }
    }

    /* -----------------------------------------------------------
     * 2. ボタンクリック判定
     * -----------------------------------------------------------
     * マウスの左ボタンが押されたかチェック。
     * 押されていなければボタン判定をスキップ（無駄な計算を避ける）。 */
    if (IsMouseButtonPressed(MOUSE_BUTTON_LEFT))
    {
        Vector2 pos = GetMousePosition(); /* クリック位置を取得 */

        /* --- 各ボタンの矩形を定義 ---
         * ボタンは画面中央に縦に並んでいる。
         * X座標: (SCREEN_WIDTH - BUTTON_WIDTH) / 2 で中央寄せ
         * Y座標: 各ボタンごとに固定値。間隔は約90ピクセル。
         *
         * 【ボタンの配置】
         * y=300: タイムアタック
         * y=390: サバイバル
         * y=480: マラソン
         * y=620: スコア一覧（少し離れている） */

        /* タイムアタックボタン */
        Rectangle btnTimeAttack = {
            (float)(SCREEN_WIDTH - BUTTON_WIDTH) / 2.0f,  /* 中央寄せX座標 */
            300.0f,                                         /* Y座標 */
            (float)BUTTON_WIDTH,                            /* ボタン幅 */
            (float)BUTTON_HEIGHT                            /* ボタン高さ */
        };

        /* サバイバルボタン */
        Rectangle btnSurvival = {
            (float)(SCREEN_WIDTH - BUTTON_WIDTH) / 2.0f,
            390.0f,
            (float)BUTTON_WIDTH,
            (float)BUTTON_HEIGHT
        };

        /* マラソンボタン */
        Rectangle btnMarathon = {
            (float)(SCREEN_WIDTH - BUTTON_WIDTH) / 2.0f,
            480.0f,
            (float)BUTTON_WIDTH,
            (float)BUTTON_HEIGHT
        };

        /* スコア一覧ボタン（少し小さめ） */
        Rectangle btnScores = {
            (float)(SCREEN_WIDTH - BUTTON_WIDTH) / 2.0f,
            620.0f,
            (float)BUTTON_WIDTH,
            (float)BUTTON_HEIGHT
        };

        /* --- クリック位置と各ボタンの衝突判定 --- */
        if (CheckCollisionPointRec(pos, btnTimeAttack))
        {
            /* タイムアタックモードでゲーム開始 */
            InitGame(MODE_TIMEATTACK);
            return; /* 画面遷移したので以降の処理はスキップ */
        }

        if (CheckCollisionPointRec(pos, btnSurvival))
        {
            /* サバイバルモードでゲーム開始 */
            InitGame(MODE_SURVIVAL);
            return;
        }

        if (CheckCollisionPointRec(pos, btnMarathon))
        {
            /* マラソンモードでゲーム開始 */
            InitGame(MODE_MARATHON);
            return;
        }

        if (CheckCollisionPointRec(pos, btnScores))
        {
            /* スコア一覧画面に遷移 */
            game.screen = SCREEN_SCORES;
            return;
        }
    }
}


